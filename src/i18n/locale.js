export function readLocale() {
  return localStorage.getItem(KEY) === 'ja' ? 'ja' : 'vi';
}

export function writeLocale(locale) {
  const next = locale === 'ja' ? 'ja' : 'vi';
  localStorage.setItem(KEY, next);
  document.documentElement.lang = next === 'ja' ? 'ja' : 'vi';
  window.dispatchEvent(new Event('rikipath-locale'));
}

