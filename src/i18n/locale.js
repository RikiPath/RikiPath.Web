export function useLocale() {
  const [locale, setLocaleState] = useState(readLocale);

  useEffect(() => {
    document.documentElement.lang = locale === 'ja' ? 'ja' : 'vi';
    const sync = () => setLocaleState(readLocale());
    window.addEventListener('rikipath-locale', sync);
    return () => window.removeEventListener('rikipath-locale', sync);
  }, [locale]);

  const t = useCallback((key) => copy[locale][key] ?? copy.vi[key] ?? key, [locale]);
  const tr = useCallback((text) => ui[locale]?.[text] ?? extraTr(locale, text), [locale]);
  const setLocale = (next) => {
    writeLocale(next);
    setLocaleState(next === 'ja' ? 'ja' : 'vi');
  };

  return { locale, setLocale, t, tr };
}
