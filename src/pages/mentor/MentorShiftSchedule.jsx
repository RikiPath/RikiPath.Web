import { useMemo, useState } from 'react';
import { useMutation } from '@tanstack/react-query';
import { useLocation } from 'react-router-dom';
import { Check, Plus, Save, SlidersHorizontal } from 'lucide-react';
import { MentorShell } from '@/layouts';
import { updateMyMentorSchedule } from '@/features/scheduling/api/mentorScheduleManageApi.js';
import { useMentorScheduleWorkspace } from '@/features/scheduling/hooks/useMentorScheduleWorkspace.js';
import InteractiveSlotCalendar from '@/features/scheduling/components/InteractiveSlotCalendar.jsx';
import { describeApiError } from '@/api/apiErrors.js';
import { ContextualErrorState, Modal, RefreshingIndicator, SakuraLoader, notify } from '@/components/ui';
import {
  formatShortDateVn,
  mondayOfDateKey,
  shiftDateKey,
  toVnDateKey,
} from '@/features/scheduling/utils/calendarGeometry.js';
import {
  buildOccupiedItems,
  buildPresetCandidateSlots,
} from '@/features/scheduling/utils/slotPlannerModel.js';
import { vietnamDate } from '@/utils/vietnamDate.js';
import { useLocale } from '@/locales/locale.js';

const WEEKDAYS = [
  { id: 1, short: 'T2' },
  { id: 2, short: 'T3' },
  { id: 3, short: 'T4' },
  { id: 4, short: 'T5' },
  { id: 5, short: 'T6' },
  { id: 6, short: 'T7' },
  { id: 0, short: 'CN' },
];

const keyOf = (weekday, code) => `${weekday}-${code}`;

export default function MentorShiftSchedule() {
  const { tr, trf } = useLocale();
  const { pathname } = useLocation();
  const workspace = useMentorScheduleWorkspace({ includeCalendarStatus: false });
  const {
    scheduleQuery,
    availabilityQuery,
    slots,
    cohortSessions,
    externalBusyEvents,
    policy,
    invalidateScheduling,
    createAvailability,
    createAvailabilityBatch,
    movePendingSlot,
    deletePendingSlot,
    requestCancelSlot,
    requestChangeSlot,
  } = workspace;

  const [anchorKey, setAnchorKey] = useState(() => toVnDateKey(new Date()));
  const [selectedSlots, setSelectedSlots] = useState([]);
  const [presetModalOpen, setPresetModalOpen] = useState(false);
  const [selectedRules, setSelectedRules] = useState(() => new Set());
  const [syncedSchedule, setSyncedSchedule] = useState(undefined);
  const [actionBusy, setActionBusy] = useState(false);
  const [statusError, setStatusError] = useState('');

  if (scheduleQuery.data !== syncedSchedule) {
    setSyncedSchedule(scheduleQuery.data);
    const curDay = vietnamDate();
    const active = (scheduleQuery.data?.rules || []).filter((r) => !r.effectiveTo || r.effectiveTo >= curDay);
    setSelectedRules(new Set(active.map((r) => keyOf(r.weekday, r.daypartCode))));
  }

  const weekStart = mondayOfDateKey(anchorKey);
  const weekEnd = shiftDateKey(weekStart, 6);
  const today = vietnamDate();

  const rulePayload = useMemo(() => {
    const dayparts = policy?.dayparts || [];
    return WEEKDAYS.flatMap((d) => dayparts
      .filter((dp) => selectedRules.has(keyOf(d.id, dp.code)))
      .map((dp) => ({
        weekday: d.id,
        daypartCode: dp.code,
        localStart: `${dp.localStart}:00`,
        localEnd: `${dp.localEnd}:00`,
        effectiveFrom: today,
      })));
  }, [policy?.dayparts, selectedRules, today]);

  const occupiedItems = useMemo(
    () => buildOccupiedItems({ slots, cohortSessions, externalBusyEvents }),
    [slots, cohortSessions, externalBusyEvents]
  );

  // Live preview of 90-minute slots generated by the selected daypart cells in the Quick Preset Modal
  const presetPreview = useMemo(
    () => buildPresetCandidateSlots({
      weekStart,
      selectedRules,
      policy,
      occupiedItems,
      existingSelectedSlots: selectedSlots,
    }),
    [weekStart, selectedRules, policy, occupiedItems, selectedSlots]
  );

  const toggleRule = (weekday, code) => {
    const k = keyOf(weekday, code);
    setSelectedRules((cur) => {
      const next = new Set(cur);
      if (next.has(k)) next.delete(k);
      else next.add(k);
      return next;
    });
  };

  const applyPresetsToCalendar = () => {
    if (presetPreview.validSlots.length === 0) return;
    setSelectedSlots((cur) => {
      const existingKeys = new Set(cur.map((s) => s.key));
      const added = presetPreview.validSlots.filter((s) => !existingKeys.has(s.key));
      return [...cur, ...added];
    });
    setPresetModalOpen(false);
    notify.success(
      trf('Đã thêm {0} khung giờ 90 phút vào lịch.', { 0: presetPreview.validSlots.length }),
      tr('Bạn có thể kiểm tra trực tiếp trên lịch và nhấn "Xem & gửi đăng ký" khi hoàn tất.'),
      { key: 'mentor-preset-apply' }
    );
  };

  async function runAction(work, successTitle, { silentToast = false } = {}) {
    setActionBusy(true);
    setStatusError('');
    const toastKey = 'mentor-interactive-schedule-action';
    if (!silentToast) {
      notify.loading(tr('Đang xử lý lịch…'), '', { key: toastKey, maxWaitMs: 30000 });
    }
    try {
      const res = await work();
      await invalidateScheduling();
      if (!silentToast) {
        if (successTitle) notify.success(successTitle, '', { key: toastKey, replace: true });
        else notify.dismiss(toastKey);
      }
      return res;
    } catch (err) {
      const msg = describeApiError(err).message;
      setStatusError(msg);
      if (!silentToast) {
        notify.apiError(err, tr('Chưa cập nhật được lịch'), { key: toastKey, replace: true });
      }
      throw err;
    } finally {
      setActionBusy(false);
    }
  }

  const saveTemplate = useMutation({
    mutationFn: () => updateMyMentorSchedule({
      timeZoneId: 'Asia/Ho_Chi_Minh',
      autoPublish: false,
      effectiveFrom: today,
      rules: rulePayload,
    }),
    onSuccess: async () => {
      setStatusError('');
      await invalidateScheduling();
      notify.success(tr('Đã lưu mẫu ca mặc định.'), '', { key: 'mentor-rule-save' });
    },
    onError: (err) => {
      const msg = describeApiError(err).message;
      setStatusError(msg);
      notify.apiError(err, tr('Chưa lưu được mẫu ca'), { key: 'mentor-rule-save-err' });
    },
  });

  const missingSchedule = scheduleQuery.error?.status === 404;
  const loadBlocked = Boolean(scheduleQuery.error && !missingSchedule && availabilityQuery.isError);
  const refreshing = availabilityQuery.isFetching || scheduleQuery.isFetching;

  return (
    <MentorShell pathname={pathname} breadcrumb={tr('Đăng ký lịch dạy')}>
      <div className="rp-container pt-2.5 pb-1.5 text-rp-text space-y-2">
        <header className="flex flex-wrap items-center justify-between gap-2">
          <div className="min-w-0">
            <h1 className="text-[20px] font-bold tracking-tight text-rp-text">{tr('Đăng ký lịch dạy')}</h1>
            <p className="text-[12.5px] text-rp-text-muted">
              {trf('Chọn nhiều khung giờ {0} phút trên lịch (nghỉ tối thiểu {1} phút giữa hai buổi), sau đó gửi đăng ký một lần.', {
                0: policy.sessionMinutes,
                1: policy.restMinutes,
              })}
            </p>
          </div>
          <RefreshingIndicator active={refreshing && !availabilityQuery.isPending} />
        </header>

        {statusError && (
          <div role="alert" className="rounded-xl border border-red-200 bg-red-50 px-4 py-2 text-[12.5px] font-medium text-red-800">
            {statusError}
          </div>
        )}

        {loadBlocked ? (
          <div className="rounded-2xl border border-rp-line bg-white p-5">
            <ContextualErrorState
              error={availabilityQuery.error || scheduleQuery.error}
              title={tr('Chưa tải được dữ liệu lịch dạy')}
              onRetry={() => { availabilityQuery.refetch(); scheduleQuery.refetch(); }}
              retrying={refreshing}
            />
          </div>
        ) : availabilityQuery.isPending ? (
          <div className="rounded-2xl border border-rp-line bg-white p-8">
            <SakuraLoader variant="section" context="calendar" label={tr('Đang tải lịch dạy…')} delay={160} />
          </div>
        ) : (
          <InteractiveSlotCalendar
            slots={slots}
            cohortSessions={cohortSessions}
            externalBusyEvents={externalBusyEvents}
            policy={policy}
            anchorKey={anchorKey}
            onAnchorChange={setAnchorKey}
            selectedSlots={selectedSlots}
            onSelectedSlotsChange={setSelectedSlots}
            refreshing={refreshing}
            busy={actionBusy}
            onRefresh={() => { availabilityQuery.refetch(); scheduleQuery.refetch(); }}
            onCreateAvailability={async ({ startTime, endTime, repeatUntil, weekdays, idempotencyKey, count, silentToast }) => {
              await runAction(
                () => createAvailability({ startTime, endTime, repeatUntil, weekdays, idempotencyKey }),
                count > 1
                  ? trf('Đã gửi {0} khung giờ 90 phút chờ duyệt.', { 0: count })
                  : tr('Đã gửi khung giờ 90 phút chờ duyệt.'),
                { silentToast }
              );
            }}
            onCreateAvailabilityBatch={async ({ slots: batchSlots, idempotencyKey, count }) => {
              await runAction(
                () => createAvailabilityBatch({ slots: batchSlots, idempotencyKey }),
                count > 1
                  ? trf('Đã gửi đăng ký {0} khung giờ 90 phút chờ duyệt.', { 0: count })
                  : tr('Đã gửi khung giờ 90 phút chờ duyệt.')
              );
            }}
            onMovePendingSlot={async ({ slot, startUtcIso, endUtcIso }) => {
              await runAction(
                () => movePendingSlot({ slot, startUtcIso, endUtcIso }),
                tr('Đã dời khung giờ chờ duyệt.')
              );
            }}
            onDeletePendingSlot={async (slotId) => {
              await runAction(() => deletePendingSlot(slotId), tr('Đã hủy khung giờ chờ duyệt.'));
            }}
            onRequestCancelSlot={async (slotId, reason) => {
              await runAction(() => requestCancelSlot(slotId, reason), tr('Đã gửi yêu cầu hủy khung giờ.'));
            }}
            onRequestChangeSlot={async (slotId, reason) => {
              await runAction(() => requestChangeSlot(slotId, reason), tr('Đã gửi yêu cầu điều chỉnh giờ.'));
            }}
            renderCustomHeaderActions={(
              <button
                type="button"
                data-testid="open-quick-preset-modal-btn"
                onClick={() => setPresetModalOpen(true)}
                className="inline-flex h-8.5 items-center gap-1.5 rounded-xl border border-rp-line bg-white px-3 text-[12px] font-semibold text-rp-text-2 hover:border-rp-brand-border hover:bg-rp-brand-tint hover:text-rp-brand-strong"
              >
                <SlidersHorizontal className="h-3.5 w-3.5 text-rp-brand-strong" />
                <span>{tr('Điền nhanh')}</span>
              </button>
            )}
          />
        )}
      </div>

      {/* Quick Preset Modal ("Điền nhanh theo ca mẫu") */}
      {presetModalOpen && (
        <Modal
          open={presetModalOpen}
          onClose={() => setPresetModalOpen(false)}
          title={tr('Điền nhanh khung giờ theo ca')}
          description={trf('Chọn các buổi trong tuần ({0} – {1}). Hệ thống tự chia thành các khung {2} phút hợp lệ cách nhau {3} phút nghỉ để bạn xem lại trên lịch trước khi gửi.', {
            0: formatShortDateVn(weekStart),
            1: formatShortDateVn(weekEnd),
            2: policy.sessionMinutes,
            3: policy.restMinutes,
          })}
          size="lg"
          footer={(
            <div className="flex w-full flex-wrap items-center justify-between gap-2">
              <button
                type="button"
                disabled={saveTemplate.isPending || actionBusy}
                onClick={() => saveTemplate.mutate()}
                className="inline-flex h-9 items-center gap-1.5 rounded-xl border border-rp-line bg-white px-3 text-[12px] font-semibold text-rp-text-2 hover:bg-rp-brand-tint disabled:opacity-50"
              >
                <Save className="h-3.5 w-3.5" />
                <span>{saveTemplate.isPending ? tr('Đang lưu…') : tr('Lưu mẫu ca mặc định')}</span>
              </button>
              <div className="flex items-center gap-2">
                <button
                  type="button"
                  onClick={() => setPresetModalOpen(false)}
                  className="inline-flex h-9 items-center rounded-xl border border-rp-line bg-white px-3.5 text-[12.5px] font-semibold text-rp-text-2 hover:bg-rp-bg-2"
                >
                  {tr('Hủy')}
                </button>
                <button
                  type="button"
                  data-testid="apply-preset-to-calendar-btn"
                  disabled={presetPreview.validSlots.length === 0}
                  onClick={applyPresetsToCalendar}
                  className="inline-flex h-9 items-center gap-1.5 rounded-xl bg-rp-brand-pressed px-4 text-[12.5px] font-semibold text-white hover:bg-rp-brand-strong disabled:opacity-50"
                >
                  <Plus className="h-3.5 w-3.5" />
                  <span>
                    {presetPreview.validSlots.length > 0
                      ? trf('Thêm vào lịch ({0})', { 0: presetPreview.validSlots.length })
                      : tr('Thêm vào lịch')}
                  </span>
                </button>
              </div>
            </div>
          )}
        >
          <div className="space-y-4">
            <div className="overflow-x-auto rounded-xl border border-rp-line">
              <table className="w-full min-w-[500px] border-collapse text-[12.5px]">
                <thead>
                  <tr className="border-b border-rp-line bg-[#FAF7F9] text-left text-rp-text-muted">
                    <th className="px-3.5 py-2.5 font-semibold">{tr('Buổi trong ngày')}</th>
                    {WEEKDAYS.map((w) => (
                      <th key={w.id} className="px-1.5 py-2.5 text-center font-semibold">{w.short}</th>
                    ))}
                  </tr>
                </thead>
                <tbody className="divide-y divide-rp-line/60">
                  {(policy?.dayparts || []).map((dp) => (
                    <tr key={dp.code} className="bg-white">
                      <td className="px-3.5 py-2.5 font-medium text-rp-text">
                        {tr(dp.label)}{' '}
                        <span className="text-[11.5px] text-rp-text-muted">({dp.localStart}–{dp.localEnd})</span>
                      </td>
                      {WEEKDAYS.map((w) => {
                        const active = selectedRules.has(keyOf(w.id, dp.code));
                        return (
                          <td key={w.id} className="px-1.5 py-2 text-center">
                            <button
                              type="button"
                              aria-pressed={active}
                              onClick={() => toggleRule(w.id, dp.code)}
                              className={`inline-flex h-8 w-10 items-center justify-center rounded-lg border text-[12px] font-semibold transition ${
                                active
                                  ? 'border-rp-brand-strong bg-rp-brand-pressed text-white shadow-2xs'
                                  : 'border-rp-line bg-white text-rp-text-muted hover:bg-rp-brand-tint'
                              }`}
                            >
                              {active ? <Check className="h-3.5 w-3.5" /> : '—'}
                            </button>
                          </td>
                        );
                      })}
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>

            {/* Preview Summary inside Modal */}
            <div className="rounded-xl border border-rp-line bg-[#FAF7F9] p-3 text-[12.5px]">
              <div className="flex flex-wrap items-center justify-between gap-2">
                <span className="font-semibold text-rp-text">
                  {presetPreview.validSlots.length > 0
                    ? trf('Sẵn sàng thêm {0} khung giờ 90 phút hợp lệ vào tuần đang xem.', { 0: presetPreview.validSlots.length })
                    : tr('Chọn các ô thứ/buổi phía trên để tạo khung giờ 90 phút cho tuần đang xem.')}
                </span>
                {presetPreview.skippedSlots.length > 0 && (
                  <span className="text-[11.5px] text-rp-text-muted">
                    {trf('Đã tự bỏ qua {0} khung trùng với lịch hiện có', { 0: presetPreview.skippedSlots.length })}
                  </span>
                )}
              </div>
              {presetPreview.validSlots.length > 0 && (
                <div className="mt-2 flex max-h-28 flex-wrap gap-1.5 overflow-y-auto">
                  {presetPreview.validSlots.slice(0, 24).map((slot) => (
                    <span
                      key={slot.key}
                      className="inline-flex items-center gap-1 rounded-full border border-emerald-200 bg-[#F0FDF4] px-2.5 py-0.5 text-[11px] font-semibold text-emerald-900"
                    >
                      <span>{formatShortDateVn(slot.dayKey)}</span>
                      <span>·</span>
                      <span className="tabular-nums">{slot.startClock}–{slot.endClock}</span>
                    </span>
                  ))}
                  {presetPreview.validSlots.length > 24 && (
                    <span className="text-[11px] text-rp-text-muted">+{presetPreview.validSlots.length - 24}</span>
                  )}
                </div>
              )}
            </div>
          </div>
        </Modal>
      )}
    </MentorShell>
  );
}
